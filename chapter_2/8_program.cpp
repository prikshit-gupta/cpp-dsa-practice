#include <iostream>
using namespace std;

int main() {

  cout << (2 < 3) << endl;  // true->1
  cout << (2 > 3) << endl;  // flase->0
  cout << (2 <= 3) << endl; // true->1
  cout << (2 >= 3) << endl; // false->0
  cout << (2 == 3) << endl; // false ->0
  cout << (2 != 3) << endl; // true->1

  return 0;
}